classdef TestModelValidation < matlab.unittest.TestCase
    methods(Test)
        function invalidConstructor(testCase)
            testCase.verifyError(@() arka.Model("4D", "Truss"), ...
                'arka:validation:InvalidDimension');
            testCase.verifyError(@() arka.Model("2D", "Solid"), ...
                'arka:validation:InvalidFamily');
        end

        function duplicateNodeAndInvalidId(testCase)
            m = arka.Model("2D", "Truss");
            m.addNode(1, [0 0]);
            testCase.verifyError(@() m.addNode(1, [1 0]), ...
                'arka:validation:DuplicateId');
            testCase.verifyError(@() m.addNode(-2, [0 0]), ...
                'arka:validation:InvalidId');
            testCase.verifyError(@() m.addNode(1.5, [0 0]), ...
                'arka:validation:InvalidId');
            testCase.verifyError(@() m.addNode(flintmax + 2, [0 0]), ...
                'arka:validation:InvalidId');
            testCase.verifyEqual(m.Revision, 1);
            testCase.verifyEqual(numel(m.listNodes()), 1);
        end

        function invalidCoordinates(testCase)
            m = arka.Model("2D", "Truss");
            testCase.verifyError(@() m.addNode(1, [1 2 3]), ...
                'arka:validation:InvalidCoordinates');
            testCase.verifyError(@() m.addNode(1, [NaN 1]), ...
                'arka:validation:InvalidCoordinates');
            testCase.verifyError(@() m.addNode(1, [Inf 1]), ...
                'arka:validation:InvalidCoordinates');
            testCase.verifyError(@() m.addNode(1, [1+2i 0]), ...
                'arka:validation:InvalidCoordinates');
            testCase.verifyError(@() m.addNode(1, [1; 2; 3]), ...
                'arka:validation:InvalidCoordinates');
            testCase.verifyEqual(m.Revision, 0);
            three = arka.Model("3D", "Frame");
            testCase.verifyError(@() three.addNode(1, [1 2]), ...
                'arka:validation:InvalidCoordinates');
        end

        function duplicateMaterialNameOrId(testCase)
            m = arka.Model("2D", "Truss");
            m.addMaterial("Steel", 'Id', 7, 'E', 200e9, 'nu', .3, 'rho', 7800);
            testCase.verifyError(@() m.addMaterial("Steel", 'E', 210e9, ...
                'nu', .3, 'rho', 7800), 'arka:validation:DuplicateName');
            testCase.verifyError(@() m.addMaterial("Other", 'Id', 7, ...
                'E', 210e9, 'nu', .3, 'rho', 7800), ...
                'arka:validation:DuplicateId');
            testCase.verifyEqual(m.Revision, 1);
        end

        function invalidMaterialProperties(testCase)
            m = arka.Model("2D", "Frame");
            testCase.verifyError(@() m.addMaterial("A", 'E', 0, ...
                'nu', .3, 'rho', 1), 'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', 1, ...
                'nu', .5, 'rho', 1), 'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', 1, ...
                'nu', -.99999999999999999, 'rho', 1), ...
                'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', 1, ...
                'nu', .2, 'rho', -1), 'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', NaN, ...
                'nu', .3, 'rho', 1), 'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', 200e9, ...
                'nu', .3, 'rho', 7850, 'G', 1), ...
                'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("A", 'E', 1, ...
                'nu', .3, 'rho', 1, 'Kind', "wood"), ...
                'arka:validation:InvalidProperty');
            testCase.verifyEqual(m.Revision, 0);
        end

        function unsupportedOrDuplicateOptions(testCase)
            m = arka.Model("2D", "Truss");
            testCase.verifyError(@() m.addMaterial("Steel", 'E', 200e9, ...
                'E', 200e9, 'nu', .3, 'rho', 7850), ...
                'arka:validation:InvalidArgument');
            testCase.verifyError(@() m.addMaterial("Steel", 'E', 200e9, ...
                'nu', .3, 'rho', 7850, 'fake', 1), ...
                'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addMaterial("Steel", 'E', 200e9, ...
                'nu', .3, 'rho'), 'arka:validation:InvalidArgument');
            testCase.verifyEqual(m.Revision, 0);
        end

        function missingMaterialReferenceAndInvalidSection(testCase)
            m = arka.Model("2D", "Truss");
            testCase.verifyError(@() m.addSection("A1", "NoSteel", 'A', .01), ...
                'arka:validation:MissingReference');
            m.addMaterial("Steel", 'E', 200e9, 'nu', .3, 'rho', 7850);
            testCase.verifyError(@() m.addSection("A1", "Steel", 'A', 0), ...
                'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addSection("A1", "Steel", 'A', .01, ...
                'J', -2), 'arka:validation:InvalidProperty');
            testCase.verifyError(@() m.addSection("A1", "Steel", 'A', .01, ...
                'Shape', "Rectangle"), 'arka:validation:InvalidProperty');
            testCase.verifyEqual(m.Revision, 1);
            testCase.verifyEmpty(m.listSections());
        end

        function duplicateSectionAndGetUnknown(testCase)
            m = arka.Model("2D", "Truss");
            m.addMaterial("Steel", 'E', 200e9, 'nu', .3, 'rho', 7850);
            m.addSection("A1", "Steel", 'Id', 4, 'A', .01);
            testCase.verifyError(@() m.addSection("A1", "Steel", 'A', .02), ...
                'arka:validation:DuplicateName');
            testCase.verifyError(@() m.addSection("B1", "Steel", ...
                'Id', 4, 'A', .02), 'arka:validation:DuplicateId');
            testCase.verifyError(@() m.getMaterial("Missing"), ...
                'arka:validation:MissingReference');
            testCase.verifyError(@() m.getNode(500), ...
                'arka:validation:UnknownRecord');
            testCase.verifyEqual(m.Revision, 2);
        end

        function emptyAndInvalidNames(testCase)
            m = arka.Model("2D", "Truss");
            testCase.verifyError(@() m.addMaterial("", 'E', 1, ...
                'nu', .2, 'rho', 0), 'arka:validation:InvalidName');
            testCase.verifyError(@() m.addMaterial("   ", 'E', 1, ...
                'nu', .2, 'rho', 0), 'arka:validation:InvalidName');
            testCase.verifyEqual(m.Revision, 0);
        end
    end
end
